"""OpenTelemetry wiring: traces, metrics and JSON logs that carry the trace ID. Vendor-neutral (OTLP/HTTP).

Generated by `eos scaffold otel-python`; yours to edit. Why and how: .eos/packs/ref/ops/opentelemetry.md

    uv add opentelemetry-sdk opentelemetry-exporter-otlp-proto-http \
        opentelemetry-instrumentation-fastapi      # or opentelemetry-instrumentation-flask

    from {{PY_PKG}}.telemetry import setup_telemetry
    app = FastAPI()            # or Flask(__name__)
    setup_telemetry(app)       # once, at startup, before the first request

Configure with the standard environment variables (https://opentelemetry.io/docs/specs/otel/configuration/sdk-environment-variables/):
    OTEL_SERVICE_NAME=my-api                          # becomes service.name (and the Prometheus job label)
    OTEL_EXPORTER_OTLP_ENDPOINT=http://collector:4318 # unset: nothing is exported, logs still get trace IDs
    OTEL_TRACES_SAMPLER=parentbased_traceidratio      # default parentbased_always_on keeps every trace
    OTEL_TRACES_SAMPLER_ARG=0.1                       # keep 10% of new traces; children follow the parent
    OTEL_RESOURCE_ATTRIBUTES=deployment.environment.name=production,service.version=1.4.2
    OTEL_SDK_DISABLED=true                            # switch it all off (tests, local)
Send to an OpenTelemetry Collector or any OTLP backend; changing vendors is a config change, not a code change.
"""

from __future__ import annotations

import json
import logging
import os
import re
import sys
from datetime import datetime, timezone
from typing import Any

HEALTH_URLS = "healthz,readyz"  # not traced: probes are noise and cost
_REDACT = re.compile(r"(?i)(password|passwd|secret|token|api_?key|authorization|cookie|card_?number|cvv)")
_STD_ATTRS = set(vars(logging.LogRecord("", 0, "", 0, "", None, None))) | {"message", "asctime", "taskName"}


def _disabled() -> bool:
    return os.environ.get("OTEL_SDK_DISABLED", "").strip().lower() == "true"


def current_trace_id() -> str | None:
    """The active trace ID as 32 hex characters, or None. Show it in error pages so users can quote it."""
    try:
        from opentelemetry import trace
    except ImportError:
        return None
    ctx = trace.get_current_span().get_span_context()
    return format(ctx.trace_id, "032x") if ctx.is_valid else None


class JsonFormatter(logging.Formatter):
    """One JSON object per line: time (UTC), level, logger, message, trace_id/span_id, and `extra` fields.

    Fields whose name looks secret are replaced with "[REDACTED]". This is a seatbelt, not a licence:
    log IDs, not values (the eos-log-secret Semgrep rule catches the obvious cases in code review).
    """

    def format(self, record: logging.LogRecord) -> str:
        out: dict[str, Any] = {
            "time": datetime.fromtimestamp(record.created, timezone.utc).isoformat(timespec="milliseconds"),
            "level": record.levelname,
            "logger": record.name,
            "message": record.getMessage(),
        }
        try:
            from opentelemetry import trace

            ctx = trace.get_current_span().get_span_context()
            if ctx.is_valid:
                out["trace_id"] = format(ctx.trace_id, "032x")
                out["span_id"] = format(ctx.span_id, "016x")
        except ImportError:
            pass
        for k, v in vars(record).items():
            if k not in _STD_ATTRS and not k.startswith("_"):
                out[k] = "[REDACTED]" if _REDACT.search(k) else v
        if record.exc_info:
            out["exception"] = self.formatException(record.exc_info)
        return json.dumps(out, default=str, ensure_ascii=False)


def configure_logging(level: str | None = None, stream: Any = None) -> None:
    """JSON logs to stdout (the platform collects them). LOG_LEVEL env var, default INFO."""
    handler = logging.StreamHandler(stream or sys.stdout)
    handler.setFormatter(JsonFormatter())
    root = logging.getLogger()
    root.handlers[:] = [handler]
    root.setLevel((level or os.environ.get("LOG_LEVEL", "INFO")).upper())


def setup_telemetry(app: Any = None, *, span_exporter: Any = None, metric_reader: Any = None) -> None:
    """Logs + traces + metrics, then instrument a FastAPI or Flask app. Safe to call when OTel is off.

    span_exporter / metric_reader: tests pass in-memory ones; production leaves them None (OTLP from env).
    """
    configure_logging()
    if _disabled():
        return
    from opentelemetry import metrics, trace
    from opentelemetry.sdk.metrics import MeterProvider
    from opentelemetry.sdk.resources import Resource
    from opentelemetry.sdk.trace import TracerProvider
    from opentelemetry.sdk.trace.export import BatchSpanProcessor, SimpleSpanProcessor

    resource = Resource.create()  # reads OTEL_SERVICE_NAME and OTEL_RESOURCE_ATTRIBUTES
    exporting = bool(
        os.environ.get("OTEL_EXPORTER_OTLP_ENDPOINT") or os.environ.get("OTEL_EXPORTER_OTLP_TRACES_ENDPOINT")
    )
    tracer_provider = TracerProvider(resource=resource)  # sampler from OTEL_TRACES_SAMPLER
    if span_exporter is not None:
        tracer_provider.add_span_processor(SimpleSpanProcessor(span_exporter))
    elif exporting:
        from opentelemetry.exporter.otlp.proto.http.trace_exporter import OTLPSpanExporter

        tracer_provider.add_span_processor(BatchSpanProcessor(OTLPSpanExporter()))
    trace.set_tracer_provider(tracer_provider)

    readers = [metric_reader] if metric_reader is not None else []
    if metric_reader is None and exporting:
        from opentelemetry.exporter.otlp.proto.http.metric_exporter import OTLPMetricExporter
        from opentelemetry.sdk.metrics.export import PeriodicExportingMetricReader

        readers.append(PeriodicExportingMetricReader(OTLPMetricExporter()))
    metrics.set_meter_provider(MeterProvider(resource=resource, metric_readers=readers))

    if app is not None:
        _instrument(app)


def _instrument(app: Any) -> None:
    kind = type(app).__module__.split(".")[0]
    if kind in ("fastapi", "starlette"):
        from opentelemetry.instrumentation.fastapi import FastAPIInstrumentor

        FastAPIInstrumentor.instrument_app(app, excluded_urls=HEALTH_URLS)
    elif kind == "flask":
        from opentelemetry.instrumentation.flask import FlaskInstrumentor

        FlaskInstrumentor().instrument_app(app, excluded_urls=HEALTH_URLS)
    else:
        logging.getLogger(__name__).warning("telemetry: no instrumentation for %s apps", kind)
