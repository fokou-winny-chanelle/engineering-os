"""Lint Alembic revisions with squawk by rendering their SQL offline (no database needed).

Generated by `eos scaffold db-safety`; yours to edit. Usage (from anywhere in the repo):
    python scripts/db/alembic_squawk.py migrations/versions/1a2b3c_add_orders.py [...]
    ALEMBIC="uv run alembic" python scripts/db/alembic_squawk.py $(git diff --name-only origin/main -- '*versions/*.py')

For each revision file it runs `alembic upgrade <down_revision>:<revision> --sql` (offline mode, see
https://alembic.sqlalchemy.org/en/latest/offline.html) next to the nearest alembic.ini, drops the
alembic_version bookkeeping statements, and pipes the SQL to squawk. Exit code 1 when squawk reports
anything, 2 when a revision cannot be rendered. Merge revisions (several down_revisions) are skipped.

Why these squawk options:
- --no-assume-in-transaction: Alembic's offline SQL already contains its BEGIN/COMMIT (and the COMMIT
  before an autocommit_block), so squawk sees the real transaction boundaries.
- require-lock-timeout / require-statement-timeout are excluded by default because the timeouts belong
  in env.py (set once per migration connection, see .eos/packs/ref/data/migrations.md); pass
  --keep-timeout-rules if you set them inside each revision instead.
- prefer-robust-stmts is excluded: the run is transactional, so a failed revision rolls back whole.
Rules excluded in .squawk.toml stay excluded. Override the commands with the ALEMBIC and SQUAWK
environment variables (defaults: "alembic" and "npx -y squawk-cli@{{SQUAWK_VERSION}}").
"""

from __future__ import annotations

import ast
import os
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

DEFAULT_EXCLUDES = ["require-lock-timeout", "require-statement-timeout", "prefer-robust-stmts"]
SQUAWK = os.environ.get("SQUAWK", "npx -y squawk-cli@{{SQUAWK_VERSION}}")
ALEMBIC = os.environ.get("ALEMBIC", "alembic")


def command(cmd: str) -> list[str]:
    """Split a command string and resolve its program on PATH (shutil.which honours PATHEXT, so `npx` finds
    npx.cmd on Windows). Windows paths keep their backslashes."""
    if os.name == "nt":
        argv = [w[1:-1] if len(w) > 1 and w[0] == w[-1] and w[0] in "\"'" else w for w in shlex.split(cmd, posix=False)]
    else:
        argv = shlex.split(cmd)
    if argv:
        argv[0] = shutil.which(argv[0]) or argv[0]
    return argv


def revision_ids(source: str) -> tuple[str | None, object]:
    """(revision, down_revision) from a revision file's module-level assignments, without importing it.
    down_revision is None (first revision), a string, or a tuple/list (merge revision)."""
    found: dict[str, object] = {}
    for node in ast.parse(source).body:
        if isinstance(node, ast.Assign):
            targets, value = node.targets, node.value
        elif isinstance(node, ast.AnnAssign) and node.value is not None:
            targets, value = [node.target], node.value
        else:
            continue
        for t in targets:
            if isinstance(t, ast.Name) and t.id in ("revision", "down_revision"):
                try:
                    found[t.id] = ast.literal_eval(value)
                except ValueError:
                    found[t.id] = None
    rev = found.get("revision")
    return (rev if isinstance(rev, str) else None), found.get("down_revision")


def strip_version_table(sql: str) -> str:
    """Drop statements that touch alembic_version (bookkeeping, not your schema)."""
    out, stmt = [], []
    for line in sql.splitlines():
        stmt.append(line)
        if line.rstrip().endswith(";"):
            text = "\n".join(stmt)
            if "alembic_version" not in text:
                out.append(text)
            stmt = []
    if stmt:
        out.append("\n".join(stmt))
    return "\n".join(out) + "\n"


def config_excludes(start: Path) -> list[str]:
    """excluded_rules from the nearest .squawk.toml (command-line --exclude takes priority over it)."""
    try:
        import tomllib  # Python 3.11+
    except ModuleNotFoundError:  # pragma: no cover - Python 3.10: rely on the defaults
        return []
    for d in [start, *start.parents]:
        f = d / ".squawk.toml"
        if f.is_file():
            with f.open("rb") as fh:
                return list(tomllib.load(fh).get("excluded_rules", []))
    return []


def find_ini(path: Path) -> Path | None:
    for d in path.resolve().parents:
        if (d / "alembic.ini").is_file():
            return d
    return None


def lint(path: Path, keep_timeouts: bool) -> int:
    rev, down = revision_ids(path.read_text(encoding="utf-8"))
    if rev is None:
        print(f"{path}: no `revision = ...` found; is this an Alembic revision file?", file=sys.stderr)
        return 2
    if isinstance(down, (tuple, list)):
        print(f"{path}: merge revision ({rev}), skipped")
        return 0
    ini_dir = find_ini(path)
    if ini_dir is None:
        print(f"{path}: no alembic.ini in any parent directory", file=sys.stderr)
        return 2
    rng = f"{down or 'base'}:{rev}"
    try:
        return _render_and_lint(path, ini_dir, rng, keep_timeouts)
    except FileNotFoundError as exc:
        print(f"{path}: command not found: {exc.filename or exc} (set ALEMBIC / SQUAWK)", file=sys.stderr)
        return 2


def _render_and_lint(path: Path, ini_dir: Path, rng: str, keep_timeouts: bool) -> int:
    r = subprocess.run(
        [*command(ALEMBIC), "upgrade", rng, "--sql"],
        cwd=ini_dir,
        capture_output=True,
        text=True,
        check=False,
        encoding="utf-8",
        errors="replace",
    )
    if r.returncode != 0:
        print(f"{path}: `alembic upgrade {rng} --sql` failed:\n{r.stderr.strip()}", file=sys.stderr)
        return 2
    excludes = sorted(
        set(([] if keep_timeouts else DEFAULT_EXCLUDES[:2]) + DEFAULT_EXCLUDES[2:] + config_excludes(ini_dir))
    )
    cmd = [*command(SQUAWK), "--no-assume-in-transaction", "--reporter", "gcc", "--stdin-filepath", str(path)]
    if excludes:
        cmd.append("--exclude=" + ",".join(excludes))
    s = subprocess.run(
        cmd,
        input=strip_version_table(r.stdout),
        capture_output=True,
        text=True,
        check=False,
        encoding="utf-8",
        errors="replace",
    )
    sys.stdout.write(s.stdout)
    sys.stderr.write(s.stderr)
    return 0 if s.returncode == 0 else 1


def main(argv: list[str]) -> int:
    for stream in (sys.stdout, sys.stderr):  # a cp1252 Windows console must not crash on squawk's output
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(errors="replace")
    keep = "--keep-timeout-rules" in argv
    files = [Path(a) for a in argv if a != "--keep-timeout-rules"]
    if not files:
        print(__doc__)
        return 0
    codes = [lint(f, keep) for f in files if f.suffix == ".py" and f.name != "__init__.py"]
    return max(codes, default=0)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
