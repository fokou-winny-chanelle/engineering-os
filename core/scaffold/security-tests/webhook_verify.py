"""Verify signed webhooks: HMAC-SHA256 over the raw body, constant-time compare, timestamp tolerance, replay guard.

Generated by `eos scaffold security-tests`. This is security-critical money code: have a human review it
against your provider's documentation before relying on it. Prefer the provider's official SDK verifier when
one exists (e.g. Stripe's `Webhook.construct_event`); use this module for providers without one.

Two schemes:
- Standard Webhooks (https://www.standardwebhooks.com/): headers `webhook-id`, `webhook-timestamp`,
  `webhook-signature` ("v1,<base64>" entries, space-separated for key rotation); signed content is
  "<id>.<timestamp>.<raw body>"; secrets are base64 with a `whsec_` prefix.
- Hex HMAC header (GitHub `X-Hub-Signature-256: sha256=<hex>` and many payment/mobile-money providers).

Rules this module enforces (docs/security refs: security/payments):
1. Verify the RAW request bytes, before any JSON parsing or re-serialisation.
2. Compare with hmac.compare_digest, never ==.
3. Reject timestamps outside the tolerance (default 300 s), in both directions.
4. Process each event id once (ReplayGuard); in production back it with a DB unique constraint.
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import hmac
import time
from collections.abc import Mapping

DEFAULT_TOLERANCE_SECONDS = 300


class WebhookVerificationError(Exception):
    """Raised for any verification failure. Respond 400/401 and do not process the event."""


def decode_standard_secret(secret: str) -> bytes:
    """Standard Webhooks secrets are base64 with a `whsec_` prefix."""
    raw = secret.removeprefix("whsec_")
    try:
        return base64.b64decode(raw, validate=True)
    except (binascii.Error, ValueError) as e:
        raise WebhookVerificationError("signing secret is not valid base64") from e


def sign_standard(key: bytes, msg_id: str, timestamp: int, body: bytes) -> str:
    """Return a `v1,<base64>` signature (used by tests and by senders)."""
    mac = hmac.new(key, f"{msg_id}.{timestamp}.".encode() + body, hashlib.sha256).digest()
    return "v1," + base64.b64encode(mac).decode()


def _check_timestamp(ts: str | None, tolerance: int, now: float | None) -> int:
    try:
        ts_i = int(ts or "")
    except ValueError as e:
        raise WebhookVerificationError("missing or invalid timestamp") from e
    current = time.time() if now is None else now
    if abs(current - ts_i) > tolerance:
        raise WebhookVerificationError("timestamp outside tolerance (possible replay)")
    return ts_i


def verify_standard(
    key: bytes,
    headers: Mapping[str, str],
    body: bytes,
    *,
    tolerance: int = DEFAULT_TOLERANCE_SECONDS,
    now: float | None = None,
) -> str:
    """Verify a Standard Webhooks request. Returns the webhook id (use it for de-duplication)."""
    if not isinstance(body, bytes | bytearray):
        raise TypeError("pass the raw request body as bytes, not parsed JSON")
    h = {k.lower(): v for k, v in headers.items()}
    msg_id, sigs = h.get("webhook-id"), h.get("webhook-signature")
    if not msg_id or not sigs:
        raise WebhookVerificationError("missing webhook-id or webhook-signature header")
    ts = _check_timestamp(h.get("webhook-timestamp"), tolerance, now)
    expected = sign_standard(key, msg_id, ts, bytes(body)).split(",", 1)[1].encode()
    for entry in sigs.split():
        version, _, sig = entry.partition(",")
        if version == "v1" and hmac.compare_digest(sig.encode(), expected):
            return msg_id
    raise WebhookVerificationError("no valid signature")


def verify_hex_hmac(secret: bytes, body: bytes, header_value: str | None, *, prefix: str = "sha256=") -> None:
    """Verify `<prefix><hex HMAC-SHA256 of body>` (GitHub X-Hub-Signature-256 style). Add your provider's
    timestamp check separately if it signs one; without a timestamp, the replay guard is your only replay defence."""
    if not isinstance(body, bytes | bytearray):
        raise TypeError("pass the raw request body as bytes, not parsed JSON")
    if not header_value or not header_value.startswith(prefix):
        raise WebhookVerificationError("missing or malformed signature header")
    expected = hmac.new(secret, bytes(body), hashlib.sha256).hexdigest()
    if not hmac.compare_digest(header_value[len(prefix) :].strip().lower().encode(), expected.encode()):
        raise WebhookVerificationError("signature mismatch")


class ReplayGuard:
    """Remembers processed event ids. In-memory version for tests and single-process apps only.

    Production: insert the event id into a table with a UNIQUE constraint in the same transaction as the
    side effect (ledger entry, fulfilment); a unique-violation means "already processed, return 200".
    """

    def __init__(self, ttl_seconds: int = 7 * 24 * 3600) -> None:
        self.ttl = ttl_seconds
        self._seen: dict[str, float] = {}

    def first_time(self, event_id: str, *, now: float | None = None) -> bool:
        current = time.time() if now is None else now
        self._seen = {k: t for k, t in self._seen.items() if current - t < self.ttl}
        if event_id in self._seen:
            return False
        self._seen[event_id] = current
        return True
