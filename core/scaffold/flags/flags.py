"""Feature flags through OpenFeature, the vendor-neutral flag API (https://openfeature.dev).

Generated by `eos scaffold flags`; yours to edit. Why and how: .eos/packs/ref/ops/feature-flags.md

    uv add openfeature-sdk

    from {{PY_PKG}}.flags import flag_enabled, setup_flags
    setup_flags()                                   # once at startup
    if flag_enabled("new-checkout", user_id=str(user.id)):
        ...

Values come from ops/flags.json (the registry that `eos ops check` validates), overridden per deployment by
FLAG_<KEY> env vars (FLAG_NEW_CHECKOUT=true). Moving to a flag service later (flagd, a SaaS, your own) means
swapping the provider in setup_flags(); call sites keep using OpenFeature. Every evaluation adds a
`feature_flag.evaluation` event to the current trace span (OpenTelemetry semantic conventions, Development
status) so an incident timeline shows which variant a request got.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
from pathlib import Path
from typing import Any

from openfeature import api
from openfeature.evaluation_context import EvaluationContext
from openfeature.exception import ErrorCode
from openfeature.flag_evaluation import FlagResolutionDetails, Reason
from openfeature.hook import Hook
from openfeature.provider import AbstractProvider, Metadata


def _registry() -> Path:
    """FLAGS_FILE, else the nearest ops/flags.json above this file. In a container, copy ops/flags.json into the
    image (or set FLAGS_FILE); a missing registry fails at startup, not silently on every request."""
    if os.environ.get("FLAGS_FILE"):
        return Path(os.environ["FLAGS_FILE"])
    for d in Path(__file__).resolve().parents:
        if (d / "ops/flags.json").is_file():
            return d / "ops/flags.json"
    return Path("ops/flags.json")


_TRUE, _FALSE = {"1", "true", "on", "yes"}, {"0", "false", "off", "no"}


def env_name(key: str) -> str:
    return "FLAG_" + re.sub(r"[^A-Za-z0-9]", "_", key).upper()


class RegistryProvider(AbstractProvider):
    """Resolves flags from the registry file plus FLAG_* env overrides. Good for one service and a small team;
    no network, no vendor. rollout_percent buckets users by a hash of flag key + targeting key (stable)."""

    def __init__(self, path: Path | None = None, env: dict[str, str] | None = None) -> None:
        data = json.loads(Path(path or _registry()).read_text(encoding="utf-8"))
        self.flags: dict[str, dict[str, Any]] = {f["key"]: f for f in data.get("flags", [])}
        self.env = dict(os.environ if env is None else env)

    def get_metadata(self) -> Metadata:
        return Metadata(name="eos-registry")

    def _resolve(self, key: str, default: Any, ctx: EvaluationContext | None, kind: type) -> FlagResolutionDetails:
        flag = self.flags.get(key)
        if flag is None:
            return FlagResolutionDetails(
                default, error_code=ErrorCode.FLAG_NOT_FOUND, error_message=f"{key} is not in the registry"
            )
        raw = self.env.get(env_name(key))
        if raw is not None:
            value, reason, variant = _parse(raw, kind), Reason.STATIC, "env"
        elif kind is bool and flag.get("rollout_percent") is not None and flag.get("default") is not True:
            target = ctx.targeting_key if ctx else None
            if not target:
                return FlagResolutionDetails(bool(flag.get("default", default)), reason=Reason.DEFAULT, variant="off")
            bucket = int(hashlib.sha256(f"{key}:{target}".encode()).hexdigest()[:8], 16) % 100
            value = bucket < int(flag["rollout_percent"])
            reason, variant = Reason.SPLIT, "on" if value else "off"
        else:
            value, reason, variant = flag.get("default", default), Reason.STATIC, "default"
        if value is None or not _is(value, kind):
            return FlagResolutionDetails(
                default, error_code=ErrorCode.TYPE_MISMATCH, error_message=f"{key} is not a {kind.__name__}"
            )
        return FlagResolutionDetails(value, reason=reason, variant=variant)

    def resolve_boolean_details(self, flag_key, default_value, evaluation_context=None):
        return self._resolve(flag_key, default_value, evaluation_context, bool)

    def resolve_string_details(self, flag_key, default_value, evaluation_context=None):
        return self._resolve(flag_key, default_value, evaluation_context, str)

    def resolve_integer_details(self, flag_key, default_value, evaluation_context=None):
        return self._resolve(flag_key, default_value, evaluation_context, int)

    def resolve_float_details(self, flag_key, default_value, evaluation_context=None):
        return self._resolve(flag_key, default_value, evaluation_context, float)

    def resolve_object_details(self, flag_key, default_value, evaluation_context=None):
        return self._resolve(flag_key, default_value, evaluation_context, dict)


def _is(value: Any, kind: type) -> bool:
    if kind is int:
        return isinstance(value, int) and not isinstance(value, bool)
    if kind is float:
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    return isinstance(value, kind)


def _parse(raw: str, kind: type) -> Any:
    try:
        if kind is bool:
            low = raw.strip().lower()
            return True if low in _TRUE else False if low in _FALSE else None
        if kind in (int, float):
            return kind(raw)
        if kind is dict:
            return json.loads(raw)
    except ValueError:
        return None
    return raw


class TraceHook(Hook):
    """Adds a feature_flag.evaluation event to the active span. No-op without OpenTelemetry."""

    def after(self, hook_context, details, hints) -> None:
        try:
            from opentelemetry import trace
        except ImportError:
            return
        span = trace.get_current_span()
        if not span.is_recording():
            return
        attrs = {
            "feature_flag.key": details.flag_key,
            "feature_flag.provider.name": hook_context.provider_metadata.name
            if hook_context.provider_metadata
            else "unknown",
            "feature_flag.result.reason": str(getattr(details.reason, "value", details.reason) or "unknown").lower(),
        }
        if details.variant:
            attrs["feature_flag.result.variant"] = details.variant
        span.add_event("feature_flag.evaluation", attrs)


_HOOKED: list[bool] = []


def setup_flags(provider: AbstractProvider | None = None) -> None:
    api.set_provider(provider or RegistryProvider())
    if not _HOOKED:  # add the trace hook once, even if setup runs again (tests, reloads)
        api.add_hooks([TraceHook()])
        _HOOKED.append(True)


def flag_enabled(key: str, default: bool = False, user_id: str | None = None, **attrs: Any) -> bool:
    """True when the boolean flag is on for this user. Unknown flag or provider error: `default`."""
    ctx = EvaluationContext(targeting_key=user_id, attributes=attrs) if (user_id or attrs) else None
    return api.get_client().get_boolean_value(key, default, ctx)
