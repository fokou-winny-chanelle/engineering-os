"""Tracing for model calls, tools and agent runs with the OpenTelemetry GenAI semantic conventions.

Generated by `eos scaffold llm-otel`; yours to edit. The conventions are in Development status and names changed
during 2026: re-check https://github.com/open-telemetry/semantic-conventions-genai when you upgrade.
Content capture (prompts, outputs) is OFF unless OTEL_INSTRUMENTATION_GENAI_CAPTURE_MESSAGE_CONTENT is set; redact
personal data before turning it on. Prices are not built in: fill PRICES from each provider's pricing page with
the date you checked. Ref: .eos/packs/ref/llm/observability-otel.md

    with llm_span("chat", "openai", MODEL, prompt_name=p.id, prompt_version=p.version, max_tokens=600) as span:
        r = client.responses.create(model=MODEL, input=msgs, max_output_tokens=600)
        record_openai_response(span, r)
"""

from __future__ import annotations

import os
from collections.abc import Iterator
from contextlib import contextmanager
from typing import Any

from opentelemetry import trace
from opentelemetry.trace import Span, SpanKind, Status, StatusCode

_TRACER = trace.get_tracer("app.genai")
CAPTURE_CONTENT = os.environ.get("OTEL_INSTRUMENTATION_GENAI_CAPTURE_MESSAGE_CONTENT", "").lower() in (
    "true",
    "span_only",
    "span_and_event",
)
# {"model-id": {"input": per_1m_tokens, "output": per_1m_tokens, "cached_input": per_1m_tokens, "checked": "YYYY-MM-DD"}}
PRICES: dict[str, dict[str, Any]] = {}


@contextmanager
def _span(name: str, kind: SpanKind, attrs: dict[str, Any], tracer: Any = None) -> Iterator[Span]:
    with (tracer or _TRACER).start_as_current_span(name, kind=kind) as span:
        for k, v in attrs.items():
            if v is not None:
                span.set_attribute(k, v)
        try:
            yield span
        except Exception as exc:
            span.set_attribute("error.type", type(exc).__qualname__)
            span.set_status(Status(StatusCode.ERROR, str(exc)[:200]))
            raise


def llm_span(
    operation: str,
    provider: str,
    model: str,
    *,
    prompt_name: str | None = None,
    prompt_version: str | int | None = None,
    max_tokens: int | None = None,
    attributes: dict[str, Any] | None = None,
    tracer: Any = None,
):
    """One CLIENT span per model call, named "{operation} {model}" (e.g. "chat gpt-6-luna")."""
    attrs = {
        "gen_ai.operation.name": operation,
        "gen_ai.provider.name": provider,
        "gen_ai.request.model": model,
        "gen_ai.request.max_tokens": max_tokens,
        "gen_ai.prompt.name": prompt_name,
        "gen_ai.prompt.version": None if prompt_version is None else str(prompt_version),
        **(attributes or {}),
    }
    return _span(f"{operation} {model}", SpanKind.CLIENT, attrs, tracer)


def tool_span(tool_name: str, *, attributes: dict[str, Any] | None = None, tracer: Any = None):
    return _span(
        f"execute_tool {tool_name}",
        SpanKind.INTERNAL,
        {"gen_ai.operation.name": "execute_tool", "gen_ai.tool.name": tool_name, **(attributes or {})},
        tracer,
    )


def agent_span(agent_name: str, *, conversation_id: str | None = None, tracer: Any = None):
    attrs = {
        "gen_ai.operation.name": "invoke_agent",
        "gen_ai.agent.name": agent_name,
        "gen_ai.conversation.id": conversation_id,
    }
    return _span(f"invoke_agent {agent_name}", SpanKind.INTERNAL, attrs, tracer)


def record_usage(
    span: Span,
    *,
    response_model: str | None = None,
    input_tokens: int | None = None,
    output_tokens: int | None = None,
    cache_read_tokens: int | None = None,
    finish_reasons: list[str] | None = None,
) -> float | None:
    """Set usage attributes; returns an estimated cost when PRICES has the model (else None)."""
    for k, v in (
        ("gen_ai.response.model", response_model),
        ("gen_ai.usage.input_tokens", input_tokens),
        ("gen_ai.usage.output_tokens", output_tokens),
        ("gen_ai.usage.cache_read.input_tokens", cache_read_tokens),
    ):
        if v is not None:
            span.set_attribute(k, v)
    if finish_reasons:
        span.set_attribute("gen_ai.response.finish_reasons", list(finish_reasons))
    cost = estimate_cost(response_model or "", input_tokens or 0, output_tokens or 0, cache_read_tokens or 0)
    if cost is not None:
        span.set_attribute("app.genai.cost_estimate", cost)
    return cost


def estimate_cost(model: str, input_tokens: int, output_tokens: int, cached: int = 0) -> float | None:
    p = PRICES.get(model)
    if not p:
        return None
    fresh = max(input_tokens - cached, 0)
    cached_rate = p.get("cached_input", p["input"])
    return (fresh * p["input"] + cached * cached_rate + output_tokens * p["output"]) / 1_000_000


def record_openai_response(span: Span, r: Any) -> float | None:
    """Usage from an OpenAI Responses API result (r.model, r.usage, r.status)."""
    u = getattr(r, "usage", None)
    details = getattr(u, "input_tokens_details", None)
    status = getattr(r, "status", None)
    return record_usage(
        span,
        response_model=getattr(r, "model", None),
        input_tokens=getattr(u, "input_tokens", None),
        output_tokens=getattr(u, "output_tokens", None),
        cache_read_tokens=getattr(details, "cached_tokens", None),
        finish_reasons=[status] if status else None,
    )


def record_content(span: Span, key: str, value: str) -> None:
    """gen_ai.input.messages / gen_ai.output.messages etc. are opt-in (personal data): only when enabled."""
    if CAPTURE_CONTENT:
        span.set_attribute(key, value)
